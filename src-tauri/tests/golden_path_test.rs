/// Test that validation catches scene without assets when adding clips.
#[test]
fn validation_catches_incomplete_scene_for_timeline() -> Result<(), AppError> {
    let env = TestEnvironment::new()?;
    let conn = env.db().conn();

    let project = Project::new("Test", "topic", "style")?;
    project_repository::insert(&conn, &project)?;

    let scene = Scene::new(project.id, 1, "Scene 1")?;
    scene_repository::insert(&conn, &scene)?;

    let timeline = Timeline::new(project.id);
    timeline_repository::insert(&conn, &timeline)?;

    // Only create image asset (missing video and audio)
    let image_asset = Asset::new(scene.id, AssetType::Image);
    asset_repository::insert(&conn, &image_asset)?;

    // Cannot add video clip because video asset doesn't exist
    let result =
        asset_validation::validate_scene_has_asset_type(&conn, scene.id, AssetType::Video);
    assert!(result.is_err());

    // Comprehensive scene validation should fail
    let result = asset_validation::validate_scene_has_all_assets(&conn, scene.id);
    assert!(result.is_err());

    Ok(())
}
