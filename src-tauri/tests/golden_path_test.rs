//! Golden Path Integration Test
//!
//! Tests the complete end-to-end workflow from project creation to final render.
//! This test validates that all Core components work together correctly.
//!
//! Workflow:
//! 1. Create project
//! 2. Create scenes manually (script generation would require API calls)
//! 3. Generate mock assets (image, video, audio) for each scene
//! 4. Create timeline
//! 5. Add clips to timeline
//! 6. Validate timeline is ready
//! 7. Verify all validation functions work correctly

mod helpers;

use combain_studio_lib::domain::asset::{Asset, AssetType};
use combain_studio_lib::domain::asset_version::AssetVersion;
use combain_studio_lib::domain::project::Project;
use combain_studio_lib::domain::scene::Scene;
use combain_studio_lib::domain::timeline::Timeline;
use combain_studio_lib::domain::timeline_clip::{TimelineClip, Track};
use combain_studio_lib::error::AppError;
use combain_studio_lib::repository::{
    asset_repository, asset_version_repository, project_repository, scene_repository,
    timeline_clip_repository, timeline_repository,
};
use combain_studio_lib::validation::{
    asset_validation, project_validation, scene_validation, timeline_validation,
};

use helpers::*;

/// Golden Path: Full workflow from project to validated timeline.
///
/// This test simulates the complete user journey without calling external APIs.
#[test]
fn golden_path_creates_project_to_validated_timeline() -> Result<(), AppError> {
    // ────────────────────────────────────────────────────────────────────────
    // Setup
    // ────────────────────────────────────────────────────────────────────────
    let env = TestEnvironment::new()?;
    let conn = env.db().conn();

    // ────────────────────────────────────────────────────────────────────────
    // Step 1: Create Project
    // ────────────────────────────────────────────────────────────────────────
    let project = Project::new(
        "Golden Path Test Project",
        "AI automation testing",
        "technical demonstration",
    )?;
    project_repository::insert(&conn, &project)?;

    // Validate project exists
    let validated_project = project_validation::validate_project_exists(&conn, project.id)?;
    assert_eq!(validated_project.id, project.id);
    assert_eq!(validated_project.name, "Golden Path Test Project");

    // Validate project is complete
    project_validation::validate_project_complete(&conn, project.id)?;

    // ────────────────────────────────────────────────────────────────────────
    // Step 2: Create Scenes
    // ────────────────────────────────────────────────────────────────────────
    // In a real workflow, these would come from generate_script
    // Here we create them manually to avoid API calls
    let scene1 = Scene::new(project.id, 1, "Introduction to the system")?;
    let scene2 = Scene::new(project.id, 2, "Core features demonstration")?;
    let scene3 = Scene::new(project.id, 3, "Conclusion and next steps")?;

    scene_repository::insert(&conn, &scene1)?;
    scene_repository::insert(&conn, &scene2)?;
    scene_repository::insert(&conn, &scene3)?;

    let scenes = vec![scene1.clone(), scene2.clone(), scene3.clone()];

    // Validate scenes exist
    let validated_scenes = scene_validation::validate_scenes_exist(&conn, project.id)?;
    assert_eq!(validated_scenes.len(), 3);

    // Validate scene order
    scene_validation::validate_scene_order(&validated_scenes)?;

    // Validate scene count
    scene_validation::validate_scene_count(&validated_scenes, 3)?;

    // ────────────────────────────────────────────────────────────────────────
    // Step 3: Generate Assets for Each Scene
    // ────────────────────────────────────────────────────────────────────────
    // In a real workflow, these would be generated by providers
    // Here we create mock assets to avoid API calls
    for scene in &scenes {
        // Create Image Asset
        let image_asset = Asset::new(scene.id, AssetType::Image);
        asset_repository::insert(&conn, &image_asset)?;

        let image_path = env
            .data_root
            .join("projects")
            .join(project.id.to_string())
            .join("assets")
            .join(image_asset.id.to_string())
            .join("v1.png");
        create_mock_png(&image_path)?;

        let image_version = AssetVersion::new(
            image_asset.id,
            1,
            image_path,
            "mock_provider",
            "mock-model",
            "Mock image prompt",
        )?;
        asset_version_repository::insert(&conn, &image_version)?;
        asset_version_repository::select_version(&conn, image_asset.id, image_version.id)?;

        // Create Video Asset
        let video_asset = Asset::new(scene.id, AssetType::Video);
        asset_repository::insert(&conn, &video_asset)?;

        let video_path = env
            .data_root
            .join("projects")
            .join(project.id.to_string())
            .join("assets")
            .join(video_asset.id.to_string())
            .join("v1.mp4");
        create_mock_mp4(&video_path)?;

        let video_version = AssetVersion::new(
            video_asset.id,
            1,
            video_path,
            "mock_provider",
            "mock-model",
            "Mock video prompt",
        )?;
        asset_version_repository::insert(&conn, &video_version)?;
        asset_version_repository::select_version(&conn, video_asset.id, video_version.id)?;

        // Create Audio Asset
        let audio_asset = Asset::new(scene.id, AssetType::Audio);
        asset_repository::insert(&conn, &audio_asset)?;

        let audio_path = env
            .data_root
            .join("projects")
            .join(project.id.to_string())
            .join("assets")
            .join(audio_asset.id.to_string())
            .join("v1.mp3");
        create_mock_mp3(&audio_path)?;

        let audio_version = AssetVersion::new(
            audio_asset.id,
            1,
            audio_path,
            "mock_provider",
            "mock-model",
            "Mock audio narration",
        )?;
        asset_version_repository::insert(&conn, &audio_version)?;
        asset_version_repository::select_version(&conn, audio_asset.id, audio_version.id)?;

        // Validate all asset types exist for this scene
        asset_validation::validate_scene_has_asset_type(&conn, scene.id, AssetType::Image)?;
        asset_validation::validate_scene_has_asset_type(&conn, scene.id, AssetType::Video)?;
        asset_validation::validate_scene_has_asset_type(&conn, scene.id, AssetType::Audio)?;

        // Validate all assets have complete versions
        asset_validation::validate_scene_has_all_assets(&conn, scene.id)?;

        // Check no missing asset types
        let missing = asset_validation::check_missing_asset_types(&conn, scene.id)?;
        assert!(missing.is_empty(), "Scene should have all asset types");
    }

    // ────────────────────────────────────────────────────────────────────────
    // Step 4: Create Timeline
    // ────────────────────────────────────────────────────────────────────────
    let timeline = Timeline::new(project.id);
    timeline_repository::insert(&conn, &timeline)?;

    // Validate timeline exists
    let validated_timeline = timeline_validation::validate_timeline_exists(&conn, project.id)?;
    assert_eq!(validated_timeline.id, timeline.id);

    // ────────────────────────────────────────────────────────────────────────
    // Step 5: Add Clips to Timeline
    // ────────────────────────────────────────────────────────────────────────
    let mut current_time = 0u64;

    for scene in &scenes {
        // Get assets for this scene
        let assets = asset_repository::list_by_scene(&conn, scene.id)?;

        let video_asset = assets
            .iter()
            .find(|a| a.asset_type == AssetType::Video)
            .expect("video asset");
        let audio_asset = assets
            .iter()
            .find(|a| a.asset_type == AssetType::Audio)
            .expect("audio asset");

        // Add video clip (5 seconds)
        let video_clip =
            TimelineClip::new(timeline.id, video_asset.id, Track::Video, current_time, 5000)?;
        timeline_clip_repository::insert(&conn, &video_clip)?;

        // Add audio clip (5 seconds, synchronized)
        let audio_clip =
            TimelineClip::new(timeline.id, audio_asset.id, Track::Audio, current_time, 5000)?;
        timeline_clip_repository::insert(&conn, &audio_clip)?;

        current_time += 5000; // Next scene starts 5 seconds later
    }

    // ────────────────────────────────────────────────────────────────────────
    // Step 6: Validate Timeline
    // ────────────────────────────────────────────────────────────────────────
    // Validate timeline has clips
    let clips = timeline_validation::validate_timeline_has_clips(&conn, timeline.id)?;
    assert_eq!(clips.len(), 6); // 3 scenes × 2 clips (video + audio)

    // Validate all clips have valid assets
    timeline_validation::validate_all_clips_have_assets(&conn, timeline.id)?;

    // Validate all clip assets have selected versions
    timeline_validation::validate_all_clip_assets_have_selected_versions(&conn, timeline.id)?;

    // Comprehensive validation: timeline ready for render
    let ready_timeline =
        timeline_validation::validate_timeline_ready_for_render(&conn, project.id)?;
    assert_eq!(ready_timeline.id, timeline.id);

    // ────────────────────────────────────────────────────────────────────────
    // Step 7: Verify All Validation Functions
    // ────────────────────────────────────────────────────────────────────────
    // This section tests that all validation points work correctly

    // Project validation
    assert!(project_validation::validate_project_exists(&conn, project.id).is_ok());
    assert!(project_validation::validate_project_complete(&conn, project.id).is_ok());

    // Scene validation
    assert!(scene_validation::validate_scenes_exist(&conn, project.id).is_ok());
    let scenes_for_validation = scene_validation::validate_scenes_exist(&conn, project.id)?;
    assert!(scene_validation::validate_scene_order(&scenes_for_validation).is_ok());
    assert!(scene_validation::validate_scene_count(&scenes_for_validation, 3).is_ok());

    // Asset validation for each scene
    for scene in &scenes {
        assert!(
            asset_validation::validate_scene_has_asset_type(&conn, scene.id, AssetType::Image)
                .is_ok()
        );
        assert!(
            asset_validation::validate_scene_has_asset_type(&conn, scene.id, AssetType::Video)
                .is_ok()
        );
        assert!(
            asset_validation::validate_scene_has_asset_type(&conn, scene.id, AssetType::Audio)
                .is_ok()
        );

        let scene_assets = asset_repository::list_by_scene(&conn, scene.id)?;
        for asset in &scene_assets {
            let version =
                asset_validation::validate_asset_has_selected_version(&conn, asset.id)?;
            assert!(asset_validation::validate_asset_file_exists(&version).is_ok());
        }

        assert!(asset_validation::validate_scene_has_all_assets(&conn, scene.id).is_ok());
    }

    // Timeline validation
    assert!(timeline_validation::validate_timeline_exists(&conn, project.id).is_ok());
    assert!(timeline_validation::validate_timeline_has_clips(&conn, timeline.id).is_ok());
    assert!(timeline_validation::validate_all_clips_have_assets(&conn, timeline.id).is_ok());
    assert!(timeline_validation::validate_all_clip_assets_have_selected_versions(
        &conn,
        timeline.id
    )
    .is_ok());
    assert!(
        timeline_validation::validate_timeline_ready_for_render(&conn, project.id).is_ok()
    );

    // ────────────────────────────────────────────────────────────────────────
    // Success!
    // ────────────────────────────────────────────────────────────────────────
    println!("✅ Golden Path test completed successfully!");
    println!("   Project: {} ({})", project.name, project.id);
    println!("   Scenes: {}", scenes.len());
    println!("   Timeline clips: {}", clips.len());
    println!("   All validation checks passed");

    Ok(())
}

/// Test that validation catches missing assets.
#[test]
fn validation_catches_missing_video_asset() -> Result<(), AppError> {
    let env = TestEnvironment::new()?;
    let conn = env.db().conn();

    let project = Project::new("Test", "topic", "style")?;
    project_repository::insert(&conn, &project)?;

    let scene = Scene::new(project.id, 1, "Scene 1")?;
    scene_repository::insert(&conn, &scene)?;

    // Only create image asset, missing video and audio
    let image_asset = Asset::new(scene.id, AssetType::Image);
    asset_repository::insert(&conn, &image_asset)?;

    // Validation should catch missing assets
    let missing = asset_validation::check_missing_asset_types(&conn, scene.id)?;
    assert!(missing.contains(&AssetType::Video));
    assert!(missing.contains(&AssetType::Audio));
    assert!(!missing.contains(&AssetType::Image));

    // Comprehensive validation should fail
    let result = asset_validation::validate_scene_has_all_assets(&conn, scene.id);
    assert!(result.is_err());

    Ok(())
}

